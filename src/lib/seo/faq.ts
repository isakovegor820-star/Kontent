/**
 * Разметка FAQPage из того же массива, что рендерит текст.
 *
 * Оговорка по отдаче: с 2023 года Google показывает расширенный сниппет FAQ только
 * для государственных и медицинских сайтов, поэтому чуда в выдаче ждать не нужно.
 * Разметка при этом остаётся полезной: её читают Яндекс, Bing и генеративные движки,
 * а стоимость её поддержки здесь нулевая — строки уже есть на странице.
 */
export function faqPageJsonLd(items: readonly FaqItem[] = FAQ_ITEMS): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: { "@type": "Answer", text: item.answer },
    })),
  };
}
