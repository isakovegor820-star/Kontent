export const DEFAULT_MOOD = "friendly";

/** Проверка, что ключ настроения валидный. */
export function isMood(key: unknown): key is string {
  return typeof key === "string" && key in MOODS;
}

/** Инструкция настроения для системного промпта (по умолчанию — дружелюбный). */
export function moodPrompt(key: string | null | undefined): string {
  return (isMood(key) ? MOODS[key] : MOODS[DEFAULT_MOOD]).prompt;
}

/** Температура генерации под настроение. */
export function moodTemp(key: string | null | undefined): number {
  return (isMood(key) ? MOODS[key] : MOODS[DEFAULT_MOOD]).temp;
}
