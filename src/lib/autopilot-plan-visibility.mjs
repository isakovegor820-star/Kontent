import { hasVerifiedQualityMetadata } from "./post-quality.mjs";

/**
 * План скрывается целиком только тогда, когда показывать нечего или показанное соврёт.
 *
 * Раньше здесь стоял второй предохранитель: любой непрошедший пост подменял весь план
 * состоянием «нужно пересобрать». Вместе с первым — воркер выбрасывал такой план ещё до
 * сохранения — это давало ровно тот результат, из-за которого автопилот выглядел
 * неработающим: пять готовых черновиков лежали в базе, а человек видел предложение
 * пересобрать. Теперь непрошедший пост доходит до человека с пометкой «нужна правка» и
 * разбором, что именно поправить.
 *
 * Публикация этим не открывается. Право на выпуск считает autopilot-approval: для
 * непрошедшего поста там остаётся блокер quality_failed, и правка перезапускает проверку.
 * Видимость и разрешение — разные вопросы, и смешивать их не нужно.
 */
export function autopilotPlanNeedsQualityRebuild(items) {
  return (Array.isArray(items) ? items : []).some(
    (item) =>
      item?.status === "pending" &&
      item?.qualityOrigin === "automatic" &&
      (
        // Показывать нечего: модель вернула заглушку вместо текста.
        item?.aiReady === false ||
        // Результата проверки нет — состояние поста неизвестно, и пометить его нечем.
        !hasVerifiedQualityMetadata(item?.quality) ||
        // Пост не прошёл проверку и при этом не помечен: в интерфейсе он выглядел бы
        // готовым. Именно эта регрессия когда-то и потребовала подмены плана.
        (item?.quality?.passed !== true && item?.reviewRequired !== true)
      ),
  );
}
