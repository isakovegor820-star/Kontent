export function guideBySlug(slug: string): Guide | undefined {
  return GUIDES.find((guide) => guide.slug === slug);
}

export function guideSlugs(): readonly string[] {
  return GUIDES.map((guide) => guide.slug);
}

/** Заголовок статьи для JSON-LD и хлебных крошек. */
export function guideBreadcrumb(guide: Guide): readonly { name: string; path: string }[] {
  return [
    { name: PRODUCT_NAME, path: "/" },
    { name: "Разборы", path: "/guide" },
    { name: guide.title, path: `/guide/${guide.slug}` },
  ];
}
