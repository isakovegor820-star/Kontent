/**
 * Автор-человек для блока доверия.
 *
 * Пока `AUTHOR` равен `null`, секция не рендерится вовсе — на странице не появляется
 * ни пустого места, ни заглушки «Имя Фамилия». Это осознанно: выдуманный автор хуже
 * отсутствующего, а тест `page.test.ts` уже запрещает выдуманные отзывы и цифры.
 *
 * Чтобы блок включился, достаточно заполнить объект. Проверять его нечем — это факт
 * о человеке, а не о коде.
 */

export type AuthorProfile = {
  /** Имя, как человек подписывается сам. */
  readonly name: string;
  /** Роль или регалия: «юрист, 12 лет практики». */
  readonly role: string;
  /** Одна строка, почему этому человеку можно верить. Без превосходных степеней. */
  readonly credential: string;
  /** Ссылка на публичный профиль: сайт практики, канал, страница на vc.ru. */
  readonly url: string;
  readonly urlLabel: string;
};

export const AUTHOR: AuthorProfile | null = null;
