/**
 * Тарифы продукта.
 *
 * Список пуст, потому что цены нет — ни в коде, ни в документации. Пустой список
 * означает «цена не опубликована», и это осознанное состояние, а не забывчивость:
 * выдуманная цена в разметке и в ответе нейросети возвращается претензиями,
 * а вопрос «сколько стоит» без ответа хуже отсутствующего вопроса.
 *
 * Как только тариф появится, он добавляется сюда одной записью — и одновременно
 * включаются три вещи, которые не могут разойтись:
 *   1. таблица «что входит и цена» на главной;
 *   2. вопрос про цену в FAQ;
 *   3. разметка SoftwareApplication с предложением, если цена публичная.
 *
 * Тест `pricing.test.ts` проверяет связку: пока список пуст, ни таблицы, ни вопроса
 * на странице нет; стоит добавить план — появляются оба.
 */

export type PricingPlan = {
  /** Название тарифа, как его увидит покупатель. */
  readonly name: string;
  /** Цена строкой: «1 900 ₽ в месяц». Число нужно и в разметке — см. `priceRub`. */
  readonly price: string;
  /** Цена числом, рублей в месяц. Нужна для структурированных данных. */
  readonly priceRub: number;
  /** Что входит — короткими пунктами, без прилагательных. */
  readonly includes: readonly string[];
  /** Для кого этот тариф, одной строкой. */
  readonly audience: string;
};

export const PRICING: readonly PricingPlan[] = Object.freeze([]);

/** Есть ли опубликованная цена. От этого зависит и таблица, и вопрос в FAQ. */
export function hasPublishedPricing(pricing: readonly PricingPlan[] = PRICING): boolean {
  return pricing.length > 0;
}
